export function getCycleConfig(slugOrId: string): EducationCycleDetails | undefined {
  const normalized = slugOrId.toLowerCase().trim();
  if (EDUCATION_CYCLES_REGISTRY[normalized]) {
    return EDUCATION_CYCLES_REGISTRY[normalized];
  }
  // Alternate aliases
  if (normalized === 'formation-professionnelle') {
    return EDUCATION_CYCLES_REGISTRY['formation_pro'];
  }
  if (normalized === 'formation_professionnelle') {
    return EDUCATION_CYCLES_REGISTRY['formation_pro'];
  }
  if (normalized === 'cfee') {
    return EDUCATION_CYCLES_REGISTRY['primaire'];
  }
  if (normalized === 'bfem') {
    return EDUCATION_CYCLES_REGISTRY['college'];
  }
  if (normalized === 'bac' || normalized === 'baccalaureat') {
    return EDUCATION_CYCLES_REGISTRY['lycee'];
  }
  if (normalized === 'lmd') {
    return EDUCATION_CYCLES_REGISTRY['universite'];
  }
  return undefined;
}

